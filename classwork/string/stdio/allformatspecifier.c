#include<stdio.h>
#include<string.h>
int main(){
	int num = 10;
	float fl = 2.50;
	double dl = 2.32000002;
	printf("Character : %c\n",'A');
	printf("integer : %d , %i\n",num,num);
	printf("octal value : %o\n",num);
	printf("hexadecimal : %x %X\n",num,num);
	printf("unsigned decimal : %u\n",255);
	printf("float value: %f\n",fl);
	printf("scientific notation : %e\n",dl);
	printf("hexadecimal scientific : %a\n",dl);
	printf("float value: %g\n",1.50000);
	printf("string : %s\n","hello world");
	
	
	
	return 0;
}
